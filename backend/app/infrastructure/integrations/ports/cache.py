from typing import Protocol


class KeyValueStore(Protocol):
    """Small Redis-compatible contract used by application cache and queue code."""

    def get(self, key: str): ...

    def set(self, key: str, value, **kwargs): ...

    def delete(self, *keys: str): ...

    def lpush(self, key: str, *values: str): ...

    def brpop(self, key: str, timeout: int = 0): ...
